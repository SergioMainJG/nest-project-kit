import { randomBytes } from "node:crypto";

import type { ProjectOptions } from "../../options/option-types.js";
import type { Blueprint, EnvVar } from "../blueprint.js";

import { BUN_VERSION } from "../versions.js";

const sorted = (entries: Iterable<[string, string]>): Record<string, string> =>
  Object.fromEntries([...entries].toSorted(([left], [right]) => left.localeCompare(right)));

export const renderPackageJson = (blueprint: Blueprint, options: ProjectOptions): string =>
  `${JSON.stringify(
    {
      dependencies: sorted(blueprint.dependencies),
      description: `NestJS ${options.app} generated by nest-project-kit`,
      devDependencies: sorted(blueprint.devDependencies),
      license: options.license === "mit" ? "MIT" : "UNLICENSED",
      name: options.name,
      packageManager: `bun@${BUN_VERSION}`,
      private: true,
      scripts: sorted(blueprint.scripts),
      type: "module",
      version: "0.1.0",
    },
    undefined,
    2,
  )}\n`;

const envLine = (variable: EnvVar, value: string): string =>
  `${variable.comment === undefined ? "" : `# ${variable.comment}\n`}${variable.optional === true && value === "" ? "# " : ""}${variable.key}=${value}`;

/** template.env: committed reference with placeholders; secrets are left empty. */
export const renderTemplateEnv = (env: readonly EnvVar[]): string =>
  `# Copy to .env (or run \`bun run secrets init\`, which also generates the secrets).\n${env
    .map((variable) => envLine(variable, variable.kind === "secret" ? "" : variable.example))
    .join("\n")}\n`;

/** .env: ready for local development, with freshly generated secrets and passwords. */
export const renderDotEnv = (
  env: readonly EnvVar[],
  random: (bytes: number) => string = (bytes) => randomBytes(bytes).toString("hex"),
): string => {
  const password = random(12);
  return `# Local development values. Never commit this file.\n${env
    .map((variable) =>
      envLine(
        variable,
        variable.kind === "secret"
          ? random(32)
          : variable.example.replaceAll("change-me", password),
      ),
    )
    .join("\n")}\n`;
};

/** test/test-env.ts: deterministic values loaded by vitest. */
export const renderTestEnv = (
  env: readonly EnvVar[],
): string => `/** Environment used by every test run (see vitest.config.ts). */
export const testEnv = {
${env
  .filter((variable) => variable.testValue !== undefined)
  .map((variable) => `  ${variable.key}: ${JSON.stringify(variable.testValue)},`)
  .join("\n")}
} as const satisfies Record<string, string>;
`;
